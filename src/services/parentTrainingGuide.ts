import { ARABIC_LETTERS_MAP } from '../data/arabicLettersData';
import type { ArabicLetterKey } from '../types/speechTherapy';

const LEGACY_GENERIC_GUIDES = [
  'التدريب أمام المرآة حسب النموذج الذي يوضحه المعلم للحرف المستهدف.',
  'اجعل الطالب ينظر في المرآة ويبتسم ابتسامة خفيفة، ثم يرفع طرف لسانه ليلامس سقف الفم خلف الأسنان مباشرة ويكرر الصوت بوضوح.',
  'اجعل الطالب ينظر في المرآة ويبتسم بهدوء ويراقب وضعية شفتيه ولسانه أثناء نطق الكلمات.'
];

/** إرشاد منزلي قابل للطباعة ومخصص للحرف، دون توجيه ولي الأمر لاستخدام أدوات داخل الفم. */
export function parentTrainingGuide(letter: ArabicLetterKey): string {
  const info = ARABIC_LETTERS_MAP[letter];
  const beginning = info.examples.beginning.words.map(item => item.word).join('، ');
  const middle = info.examples.middle.words.map(item => item.word).join('، ');
  const end = info.examples.end.words.map(item => item.word).join('، ');

  return [
    `طريقة تدريب الطالب منزلياً على حرف (${letter}):`,
    '1- التهيئة: اختر مكاناً هادئاً، واجعل مدة التدريب من 5 إلى 10 دقائق. انطق الحرف أمام الطالب بوضوح مرة واحدة، ثم اطلب منه الاستماع والملاحظة دون استعجال.',
    `2- معرفة المخرج: ${info.articulationPoint} راقب حركة أعضاء النطق من الخارج فقط، وقدّم نموذجاً صحيحاً دون إدخال أدوات داخل فم الطالب.`,
    `3- التدريب أمام المرآة: ${info.mirrorInstruction}`,
    `4- التدرج الصوتي: ابدأ بالحرف منفرداً (${info.shortVowels.sukoon})، ثم مع الحركات القصيرة (${info.shortVowels.fatha}، ${info.shortVowels.damma}، ${info.shortVowels.kasra})، وبعد نجاحه انتقل إلى الحركات الطويلة (${info.longVowels.alif}، ${info.longVowels.waw}، ${info.longVowels.yaa}). لا تنتقل إلى مستوى أصعب قبل نجاح المستوى السابق.`,
    `5- التدريب بالكلمات: درّب على كلمات أول الكلمة (${beginning})، ثم وسط الكلمة (${middle})، ثم آخر الكلمة (${end}). ينطق ولي الأمر الكلمة أولاً، ثم يكررها الطالب بهدوء، وتُسجّل علامة صح بعد كل محاولة مكتملة.`,
    `6- التعميم: بعد نجاح الكلمات، استخدم الجملة: «${info.practiceSentences[0]}»، ثم شجّع الطالب على استعمال كلمة تحتوي حرف (${letter}) في حديث يومي قصير.`,
    '7- التغذية الراجعة: امدح المحاولة الصحيحة مباشرة، وإذا أخطأ الطالب فأعد النموذج مرة واحدة واطلب محاولة جديدة دون لوم أو تكرار مُجهد. أوقف التدريب عند التعب أو الانزعاج، ودوّن الصعوبة في خانة ملاحظات ولي الأمر ليعالجها المعلم في الجلسة القادمة.'
  ].join('\n');
}

/** يولّد طريقة مختلفة حسب التوجيه الذي اختاره المعلم، مع إبقاء المحتوى خاصاً بالحرف. */
export function parentTrainingGuideForGuidance(letter: ArabicLetterKey, guidance: string): string {
  const info = ARABIC_LETTERS_MAP[letter];
  const beginning = info.examples.beginning.words.map(item => item.word).join('، ');
  const middle = info.examples.middle.words.map(item => item.word).join('، ');
  const end = info.examples.end.words.map(item => item.word).join('، ');
  const commonEnd = 'اختم بمدح المحاولة الصحيحة، وأوقف التدريب عند التعب أو الانزعاج، ودوّن الصعوبة للمعلم دون استخدام أي أداة داخل فم الطالب.';

  if (/حسب الأمثلة|الأمثلة المحددة|مراجعة حرف/.test(guidance)) {
    return [
      `مراجعة أمثلة حرف (${letter}) المحددة في الورقة:`,
      `1- ذكّر الطالب بالمخرج الصحيح قبل الكلمات: ${info.articulationPoint}`,
      `2- راجع كلمات أول الكلمة (${beginning})، ثم وسط الكلمة (${middle})، ثم آخر الكلمة (${end}) وفق ترتيب الجدول.`,
      '3- ينطق ولي الأمر كل كلمة مرة واحدة، ثم يكررها الطالب خمس مرات، وتوضع علامة صح للمحاولة المكتملة دون إضافة كلمات أصعب.',
      `4- اختم بالجملة «${info.practiceSentences[0]}»، وسجّل الموضع الذي نجح فيه الطالب والموضع الذي احتاج مساعدة.`,
      commonEnd
    ].join('\n');
  }

  if (/قصيراً|هادئاً|نموذجاً واضحاً/.test(guidance)) {
    return [
      `جلسة منزلية قصيرة وهادئة لحرف (${letter}):`,
      '1- خصص خمس دقائق في مكان هادئ، وأبعد المشتتات، وأخبر الطالب أن المطلوب محاولات قليلة صحيحة لا سرعة أو كثرة.',
      `2- قدّم نموذجاً سمعياً واضحاً للحرف (${info.shortVowels.fatha})، ثم انتظر حتى ينظر الطالب ويسمع قبل أن يقلدك.`,
      `3- نفّذ ثلاث محاولات للحرف منفرداً، ثم اختر كلمة سهلة واحدة (${info.examples.beginning.words[0].word}) وكررها ثلاث مرات فقط.`,
      '4- استخدم تعزيزاً فورياً بسيطاً بعد المحاولة الصحيحة، وأنهِ الجلسة بنجاح بدلاً من إطالتها عند انخفاض الانتباه.',
      commonEnd
    ].join('\n');
  }

  if (/المرآة|الملاحظة البصرية/.test(guidance)) {
    return [
      `تدريب المرآة الخاص بحرف (${letter}):`,
      `1- اجلس بجانب الطالب أمام مرآة واضحة، وانطق (${info.shortVowels.fatha}) ببطء حتى يرى النموذج ويسمعه في الوقت نفسه.`,
      `2- وجّه انتباهه إلى موضع النطق: ${info.articulationPoint}`,
      `3- طبّق الملاحظة البصرية: ${info.mirrorInstruction}`,
      `4- تبادلا الدور خمس مرات: ينطق ولي الأمر نموذجاً واحداً ثم يقلده الطالب، وبعد نجاح الحرف منفرداً انتقلا إلى (${info.shortVowels.damma}، ${info.shortVowels.kasra}).`,
      `5- جرّب كلمة واحدة من كل موضع: (${info.examples.beginning.words[0].word})، (${info.examples.middle.words[0].word})، (${info.examples.end.words[0].word}).`,
      commonEnd
    ].join('\n');
  }

  if (/الحركات القصيرة|الحركات الطويلة/.test(guidance)) {
    return [
      `تدريب الحركات على حرف (${letter}):`,
      `1- ابدأ بالحرف الساكن (${info.shortVowels.sukoon}) ثلاث محاولات صحيحة مع نموذج واضح من ولي الأمر.`,
      `2- درّب الحركات القصيرة بالتتابع: (${info.shortVowels.fatha}) ثم (${info.shortVowels.damma}) ثم (${info.shortVowels.kasra})، وكرر كل مقطع خمس مرات بهدوء.`,
      `3- بعد ثباتها انتقل إلى الحركات الطويلة: (${info.longVowels.alif}) ثم (${info.longVowels.waw}) ثم (${info.longVowels.yaa})، مع إطالة الحركة دون تغيير مخرج الحرف.`,
      `4- قارن بين مقطعين في كل مرة، واطلب من الطالب اختيار النطق الصحيح ثم تقليده. لا تنتقل إلى الكلمات حتى ينجح في المستوى المحدد.`,
      commonEnd
    ].join('\n');
  }

  if (/أول الكلمة/.test(guidance)) {
    return [
      `تدريب حرف (${letter}) في أول الكلمة:`,
      `1- راجع مخرج الحرف سريعاً: ${info.articulationPoint}`,
      `2- اعرض الكلمات الثلاث بالترتيب (${beginning})، وقل كل كلمة ببطء مع إبراز صوت (${letter}) في بدايتها دون فصل مبالغ فيه.`,
      '3- يكرر الطالب كل كلمة خمس مرات، وتوضع علامة صح لكل محاولة مكتملة. عند الخطأ أعد الكلمة مرة واحدة ثم اطلب المحاولة من جديد.',
      `4- استخدم جملة التطبيق: «${info.examples.beginning.words[0].sentence}»، ثم اطلب من الطالب ذكر كلمة أخرى تبدأ بحرف (${letter}).`,
      commonEnd
    ].join('\n');
  }

  if (/وسط الكلمة|آخرها|آخر الكلمة/.test(guidance)) {
    return [
      `تدريب حرف (${letter}) في وسط الكلمة وآخرها:`,
      `1- ابدأ بكلمات وسط الكلمة (${middle})، وانطقها ببطء مع إبراز موضع حرف (${letter}) ثم يكررها الطالب خمس مرات.`,
      `2- انتقل إلى كلمات آخر الكلمة (${end})، واطلب من الطالب المحافظة على الصوت حتى نهاية الكلمة دون حذفه أو استبداله.`,
      '3- بدّل بين كلمة من الوسط وكلمة من الآخر حتى يميز الطالب مكان الصوت، وسجّل علامة صح بعد كل محاولة مكتملة.',
      `4- كوّن مع الطالب جملة قصيرة بكلمة من كل مجموعة، مع تصحيح محاولة واحدة فقط في كل دور حتى لا يتحول التدريب إلى تكرار مُجهد.`,
      commonEnd
    ].join('\n');
  }

  if (/المستوى|صعوبة الأداء|المستوى الذي أتقنه/.test(guidance)) {
    return [
      `تثبيت المستوى الحالي لحرف (${letter}):`,
      '1- استخدم فقط المستوى والكلمات المحددة في ورقة الواجب، ولا تنتقل إلى مستوى جديد في المنزل.',
      `2- قدّم نموذجاً واحداً واضحاً يراعي المخرج: ${info.articulationPoint}`,
      '3- اطلب ثلاث محاولات متباعدة، وقدّم تلميحاً بصرياً أو لفظياً بسيطاً عند الحاجة. إذا تكرر الخطأ مرتين، أوقف هذا المثال وانتقل إلى مثال أسهل.',
      '4- سجّل الكلمات الناجحة والصعوبة كما حدثت فعلياً؛ ليقرر المعلم في الجلسة التالية التثبيت أو التدرج.',
      commonEnd
    ].join('\n');
  }

  if (/حديث يومي|التعميم|استخدام الحرف/.test(guidance)) {
    return [
      `تعميم حرف (${letter}) في الحديث اليومي:`,
      `1- اختر كلمتين مألوفتين من الورقة تحتويان حرف (${letter})، وراجعهما سريعاً قبل بدء النشاط اليومي.`,
      `2- استخدم الجملة النموذجية: «${info.practiceSentences[0]}»، ثم اطلب من الطالب جملة جديدة من حياته تتضمن إحدى الكلمتين.`,
      '3- نفّذ حواراً قصيراً لمدة دقيقتين؛ ذكّر الطالب بالحرف مرة واحدة في البداية، ثم اتركه يتحدث دون مقاطعة متكررة.',
      '4- امدح الاستخدام التلقائي الصحيح، وسجّل هل نطق الحرف مستقلاً أم احتاج تلميحاً، ولا تصحح كل أخطاء الحديث دفعة واحدة.',
      commonEnd
    ].join('\n');
  }

  return `${guidance}\n\n${parentTrainingGuide(letter)}`;
}

export function shouldUpgradeParentTrainingGuide(value: string | undefined): boolean {
  const normalized = value?.trim() || '';
  return !normalized
    || LEGACY_GENERIC_GUIDES.includes(normalized)
    || normalized.includes('ملاحظة حركة الفم واللسان عند نطق صوت حرف');
}
